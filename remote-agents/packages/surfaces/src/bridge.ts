/**
 * Generates the self-contained TCP↔stdio bridge script herdr panes run
 * (CONTRACT.md §3). The script itself:
 *
 *   bun bridge.mjs --port-file <file> -- <command...>
 *
 * - listens on an OS-assigned 127.0.0.1 port, writes it to the port file
 *   atomically (tmp file + rename),
 * - spawns the command with piped stdio and pumps socket↔stdio both ways,
 * - captures the worker's authentic `ready` line and replays it to every NEW
 *   client (clients that connect before it is captured get it as soon as it
 *   arrives), so a reconnecting OmpRpc can complete its handshake,
 * - survives client disconnects — the worker keeps running,
 * - exits when the child exits (port file removed), forwarding SIGTERM/SIGINT.
 *
 * No interpolation: the returned string is byte-identical on every call and
 * unit-testable.
 */
export function renderBridgeScript(): string {
  return `// remote-agents stdio<->TCP bridge (generated by @remote-agents/surfaces/src/bridge.ts)
import { renameSync, unlinkSync, writeFileSync } from "node:fs";

const argv = process.argv.slice(2);

function argAfter(name) {
  const idx = argv.indexOf(name);
  return idx >= 0 && idx + 1 < argv.length ? argv[idx + 1] : undefined;
}

const portFile = argAfter("--port-file");
const separator = argv.indexOf("--");
const command = separator >= 0 ? argv.slice(separator + 1) : [];

if (!portFile || command.length === 0) {
  process.stderr.write("usage: bun bridge.mjs --port-file <file> -- <command...>\\n");
  process.exit(2);
}

const clients = new Set();
const waitingForReady = new Set();
let readyLine = null;

const child = Bun.spawn({ cmd: command, stdin: "pipe", stdout: "pipe", stderr: "inherit" });

function toChild(chunk) {
  try {
    child.stdin.write(chunk);
    child.stdin.flush();
  } catch {
    // Child already gone; the stdout pump drives shutdown.
  }
}

const server = Bun.listen({
  hostname: "127.0.0.1",
  port: 0,
  socket: {
    open(socket) {
      clients.add(socket);
      // Every new client gets the worker's handshake frame so a fresh OmpRpc
      // can start() against the same live worker.
      if (readyLine !== null) {
        socket.write(readyLine);
      } else {
        waitingForReady.add(socket);
      }
    },
    data(_socket, chunk) {
      toChild(chunk);
    },
    close(socket) {
      clients.delete(socket);
      waitingForReady.delete(socket);
    },
    error(socket) {
      clients.delete(socket);
      waitingForReady.delete(socket);
      try {
        socket.end();
      } catch {}
    },
  },
});

function writePortFile() {
  const tmp = portFile + ".tmp." + process.pid;
  writeFileSync(tmp, String(server.port) + "\\n");
  renameSync(tmp, portFile);
}

function broadcast(chunk) {
  for (const socket of clients) {
    try {
      socket.write(chunk);
    } catch {
      clients.delete(socket);
    }
  }
}

function shutdown(exitCode) {
  try {
    unlinkSync(portFile);
  } catch {}
  try {
    server.stop(true);
  } catch {}
  for (const socket of clients) {
    try {
      socket.end();
    } catch {}
  }
  process.exit(exitCode);
}

process.on("SIGTERM", () => {
  try {
    child.kill("SIGTERM");
  } catch {}
  shutdown(143);
});
process.on("SIGINT", () => {
  try {
    child.kill("SIGINT");
  } catch {}
  shutdown(130);
});

// Scan child stdout for the ready frame while relaying every byte. The scan
// buffer holds at most one partial line; oversized garbage stops scanning.
const decoder = new TextDecoder();
let scan = "";
const SCAN_CAP = 1024 * 1024;

function scanChunk(chunk) {
  scan += decoder.decode(chunk, { stream: true });
  for (;;) {
    const nl = scan.indexOf("\\n");
    if (nl === -1) break;
    const line = scan.slice(0, nl);
    scan = scan.slice(nl + 1);
    noteLine(line);
  }
  if (scan.length > SCAN_CAP) scan = "";
}

function noteLine(line) {
  if (readyLine !== null || !line.startsWith("{")) return;
  try {
    const frame = JSON.parse(line);
    if (frame && frame.type === "ready") {
      readyLine = line + "\\n";
      for (const socket of waitingForReady) {
        try {
          socket.write(readyLine);
        } catch {}
      }
      waitingForReady.clear();
    }
  } catch {
    // Not JSON; keep scanning.
  }
}

writePortFile();

(async () => {
  const reader = child.stdout.getReader();
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (value) {
        scanChunk(value);
        broadcast(value);
      }
    }
  } catch {}
  // stdout EOF: drain the exit code, then tear everything down.
  let code = 1;
  try {
    code = await child.exited;
  } catch {}
  shutdown(typeof code === "number" ? code : 1);
})();
`;
}
